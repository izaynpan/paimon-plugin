import fs from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { recordId, resolveTraveler } from './traveler-profiles.js'

export const root = fileURLToPath(new URL('../', import.meta.url))
const digest = value => createHash('sha256').update(value).digest('hex')
const json = value => JSON.stringify(value, null, 2) + '\n'

// Only explicitly labelled speakers are accepted. Never infer a speaker from the page owner.
export function parseDialogue(body) {
  const lines = []
  for (const line of body.split(/\r?\n/).filter(x => x.trim())) {
    const match = /^\s*[●•]?\s*(派蒙|旅行者)：(.+)$/.exec(line)
    if (!match) return null
    lines.push({ speaker: match[1], text: match[2] })
  }
  return lines.some(x => x.speaker === '派蒙') && lines.some(x => x.speaker === '旅行者') ? lines : null
}

export function mergeTurns(lines) {
  const turns = []
  for (const line of lines) {
    if (turns.at(-1)?.speaker === line.speaker) turns.at(-1).text += line.text
    else turns.push({ ...line })
  }
  return turns
}

export async function buildCorpus(base = root) {
  const files = ['traveler-female.zh-CN.json', 'traveler-male.zh-CN.json']
  // Git may check text out as CRLF on Windows. Hash canonical LF text across hosts.
  const texts = await Promise.all(files.map(async file => (await fs.readFile(path.join(base, 'knowledge/characters', file), 'utf8')).replace(/\r\n/g, '\n')))
  const [female, male] = texts.map(JSON.parse)
  const profiles = [female, resolveTraveler(male, female)]
  const rows = new Map(), rejected = []
  profiles.forEach((profile, i) => {
    for (const voice of profile.语音台词) {
      if (!voice.正文.includes('派蒙：')) continue
      const lines = parseDialogue(voice.正文)
      if (!lines) { rejected.push({ file: files[i], title: voice.标题 }); continue }
      const id = recordId('语音台词', voice)
      if (!rows.has(id)) rows.set(id, { id, title: voice.标题, text: voice.正文, lines, turns: mergeTurns(lines), sources: [] })
      rows.get(id).sources.push({ file: files[i], recordId: id, traveler: i ? '空' : '荧' })
    }
  })
  return { version: 1, inputs: files.map((file, i) => ({ file, sha256: digest(texts[i]),
    voiceSources: [female, male][i].来源.补充语音来源 })),
  deduplication: '按原条目标识精确合并；男女差异保留，不合并近似语义。', rejected, records: [...rows.values()] }
}

export function compileExamples(corpus, curation) {
  const records = new Map(corpus.records.map(row => [row.id, row]))
  const examples = []
  const seen = new Set()
  for (const item of curation.entries) {
    const row = records.get(item.id)
    if (!row || row.title !== item.title || seen.has(item.id)) throw new Error('风格审阅条目缺失、变动或重复：' + item.title)
    seen.add(item.id)
    if (!item.learn || !item.avoid || !item.tags?.length) throw new Error('缺少风格审阅注记：' + item.title)
    if (!item.excerpt) continue
    if (typeof item.focus !== 'string' || !item.focus.trim()) throw new Error('节选缺少互动要点：' + item.title)
    const [start, end] = item.excerpt
    if (!Number.isInteger(start) || !Number.isInteger(end) || start < 0 || end <= start || end > row.lines.length)
      throw new Error('节选范围无效：' + item.title)
    const turns = mergeTurns(row.lines.slice(start, end))
    if (!turns.some(x => x.speaker === '旅行者') || turns.at(-1)?.speaker !== '派蒙') throw new Error('节选缺少互动或末尾不是派蒙：' + item.title)
    examples.push({ id: item.id, title: item.title, focus: item.focus, turns })
  }
  if (examples.length < 4 || examples.length > 6) throw new Error('固定示例应为 4～6 组')
  const promptData = { styleExamples: examples.map(({ focus, turns }) => ({ focus, turns })) }
  if ([...JSON.stringify(promptData)].length > 1500) throw new Error('固定示例超出预算')
  return examples
}

export async function artifacts(base = root) {
  const corpus = await buildCorpus(base)
  const curation = JSON.parse(await fs.readFile(path.join(base, 'knowledge/paimon-style/curation.json'), 'utf8'))
  const examples = compileExamples(corpus, curation)
  return new Map([
    ['knowledge/paimon-style/corpus.json', json(corpus)],
    ['lib/paimon-style-data.js', '// Generated by node scripts/paimon-style.js build; edit curation.json instead.\nexport const styleExamples = ' + JSON.stringify(examples, null, 2) + '\n'],
  ])
}

async function main() {
  const mode = process.argv[2]
  if (!['build', 'check'].includes(mode)) throw new Error('用法：node scripts/paimon-style.js build|check')
  for (const [name, value] of await artifacts()) {
    const file = path.join(root, name)
    if (mode === 'build') { await fs.mkdir(path.dirname(file), { recursive: true }); await fs.writeFile(file, value) }
    else if ((await fs.readFile(file, 'utf8')).replace(/\r\n/g, '\n') !== value) throw new Error('风格产物过期：' + name)
  }
  console.log(mode === 'build' ? '风格资料已构建；未改动知识索引。' : '风格资料与来源、审阅清单一致。')
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  main().catch(error => { console.error(error.message); process.exitCode = 1 })
